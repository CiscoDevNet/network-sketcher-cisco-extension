def main(argv: Optional[list] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Convert a CML YAML topology file into Network Sketcher commands.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--yaml", "-y",
        required=True,
        metavar="CML_TOPOLOGY.yaml",
        help="Path to a CML Lab YAML, or the JSON written by fetch_from_cml.",
    )
    parser.add_argument(
        "--configs", "-c",
        default=None,
        metavar="CONFIGS_DIR",
        help="Directory containing running-config files (*.txt / *.cfg). "
             "File stems must match CML node labels. Optional.",
    )
    parser.add_argument(
        "--out", "-o",
        default="ns_commands.txt",
        metavar="OUTPUT_FILE",
        help="Destination for the NS command script. "
             "Side-outputs (ns_model.json etc.) are written to the same directory. "
             "Default: ns_commands.txt",
    )
    parser.add_argument(
        "--layout", "-l",
        choices=["auto", "coordinate", "tier"],
        default="auto",
        help="Device placement strategy. "
             "'coordinate' mirrors the CML canvas (x, y) positions; "
             "'tier' uses the role-based hierarchy (WAN→Border→Spine→…→Endpoint); "
             "'auto' (default) uses coordinates when present, else tier.",
    )
    parser.add_argument(
        "--mode", "-m",
        choices=["underlay", "overlay", "both"],
        default="underlay",
        help="'underlay' (default) writes the physical L1/L2/L3 script as before; "
             "'overlay' writes one integrated overlay script (VXLAN EVPN, SD-WAN, "
             "L3VPN found in the configs); 'both' writes the two.",
    )
    parser.add_argument(
        "--overlay",
        choices=["auto", "evpn", "sdwan", "l3vpn"],
        action="append",
        default=None,
        metavar="TYPE",
        help="Overlay types to draw (repeatable): auto (default, every type found), "
             "evpn, sdwan, l3vpn.",
    )
    args = parser.parse_args(argv)
    write_underlay = args.mode in ("underlay", "both")
    write_overlay = args.mode in ("overlay", "both")

    yaml_path = pathlib.Path(args.yaml).resolve()
    configs_dir = pathlib.Path(args.configs).resolve() if args.configs else None
    out_path = pathlib.Path(args.out).resolve()
    out_dir = out_path.parent
    out_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # Step 1: load YAML
    # ------------------------------------------------------------------
    print(f"[1/6] Loading CML YAML: {yaml_path}")
    try:
        raw_data = _load_yaml(yaml_path)
    except FileNotFoundError:
        print(f"[ERROR] File not found: {yaml_path}", file=sys.stderr)
        return 1
    except yaml.YAMLError as exc:
        print(f"[ERROR] YAML parse error: {exc}", file=sys.stderr)
        return 1

    merged = _extract_labs(raw_data)
    if merged is not None:
        nodes, links = merged
        print(f"         labs={len(raw_data.get('labs') or [])}, "
              f"nodes={len(nodes)}, links={len(links)}")
    else:
        nodes, links = _extract_topology(raw_data)
        disambiguate_device_labels(nodes)
        print(f"         nodes={len(nodes)}, links={len(links)}")

    # ------------------------------------------------------------------
    # Step 2: stencil mapping
    # ------------------------------------------------------------------
    print("[2/6] Mapping stencils …")
    stencil_list = map_all(nodes)
    stencil_map = {s.label: s for s in stencil_list}

    csv_path = out_dir / "stencil_mapping.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerows(to_csv_rows(stencil_list))
    print(f"  stencil_mapping.csv → {csv_path}")

    low_conf = [s for s in stencil_list if s.confidence < 0.5]
    if low_conf:
        print(f"  [WARN] {len(low_conf)} device(s) have low-confidence stencil mapping "
              f"(confidence < 0.5). Review stencil_mapping.csv.")

    # ------------------------------------------------------------------
    # Step 3: running-config parsing
    # ------------------------------------------------------------------
    print("[3/6] Loading running configs …")
    if configs_dir:
        raw_configs = _rekey_configs(_load_running_configs(configs_dir), nodes)
        print(f"         source: --configs directory ({len(raw_configs)} file(s))")
    else:
        raw_configs = _extract_configs_from_nodes(nodes)
        if raw_configs:
            print(f"         source: embedded configuration_text in YAML ({len(raw_configs)} node(s))")
        else:
            print("         source: none (no --configs dir, no embedded configs in YAML)")
    parsed_configs = parse_all(raw_configs) if raw_configs else {}
    parsed_configs, not_extracted = split_day0_configs(raw_configs, parsed_configs)
    if not_extracted:
        print(f"  [WARN] {len(not_extracted)} node(s) still have CML's day-0 config "
              f"(not extracted in CML), so no L2/L3 is read for them. See parse_report.md.")
    print(f"         parsed {len(parsed_configs)} config(s)")

    # ------------------------------------------------------------------
    # Step 4: build NS model
    # ------------------------------------------------------------------
    print("[4/6] Building NS topology model …")
    model, parse_stats = build_ns_model(nodes, links, stencil_map, parsed_configs, layout=args.layout)

    if write_overlay:
        overlay_rc = _write_overlay(
            args, raw_data, yaml_path, out_path, nodes, model, stencil_map,
            raw_configs, parsed_configs, not_extracted,
        )
        if overlay_rc and not write_underlay:
            return overlay_rc
    if not write_underlay:
        print("\n[Done] All outputs written.")
        return 0

    model_path = out_dir / "ns_model.json"
    model_path.write_text(
        json.dumps(model_to_dict(model), indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    print(f"  ns_model.json    → {model_path}")
    if model.skipped_ports:
        print(f"  [WARN] {len(model.skipped_ports)} L2/L3 item(s) skipped on ports with "
              f"no L1 link. See parse_report.md.")

    # ------------------------------------------------------------------
    # Step 5: generate NS commands
    # ------------------------------------------------------------------
    print("[5/6] Generating NS commands …")
    script = build_command_script(model)
    out_path.write_text(script.text(), encoding="utf-8")
    print(f"  ns_commands.txt  → {out_path}")
    total_cmds = sum(script.counts.values())
    print(f"         {total_cmds} command(s) across {len(script.counts)} phase(s)")

    # ------------------------------------------------------------------
    # Step 6: parse report
    # ------------------------------------------------------------------
    print("[6/6] Writing parse report …")
    skipped = list(model.skipped_ports) + [
        (device, port, f"IPv6 {addr} ({reason})")
        for device, port, addr, reason in script.dropped_ips
    ]
    if script.dropped_ips:
        print(f"  [WARN] {len(script.dropped_ips)} IPv6 address(es) left out because "
              f"Network Sketcher does not accept them. See parse_report.md.")
    _write_parse_report(out_dir, parse_stats, nodes, parsed_configs, skipped, not_extracted)

    print("\n[Done] All outputs written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
